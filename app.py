STEM_LIKE = {
    "Engineering",
    "Computers & Mathematics",
    "Physical Sciences",
    "Biology & Life Science",
    "Health",
}


def build_feature_row(
    feature_cols,
    major_category,
    p25,
    p75,
    sample_size,
    unemp_rate,
    share_women,
):
    """Create a single-row DataFrame whose columns match feature_cols."""
    data = {c: 0.0 for c in feature_cols}

    # Direct numeric features – only set if they exist in training columns
    if "P25th" in data:
        data["P25th"] = p25
    if "P75th" in data:
        data["P75th"] = p75
    if "Sample_size" in data:
        data["Sample_size"] = sample_size
    if "Unemployment_rate" in data:
        data["Unemployment_rate"] = unemp_rate
    if "ShareWomen" in data:
        data["ShareWomen"] = share_women

    # Engineered features (if your training used them)
    if "Employment_Ratio" in data:
        data["Employment_Ratio"] = 1.0 - unemp_rate

    if "STEM_Flag" in data:
        data["STEM_Flag"] = 1.0 if major_category in STEM_LIKE else 0.0

    # One-hot for major category – assumes columns like "Major_category_Engineering"
    col_name = "Major_category_" + major_category.replace("&", "and").replace(" ", "_")
    if col_name in data:
        data[col_name] = 1.0

    return pd.DataFrame([data], columns=feature_cols)


